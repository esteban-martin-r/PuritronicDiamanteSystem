DELIMITER $$
CREATE TRIGGER `tr_antes_de_insertar_compra` BEFORE INSERT ON `compras` FOR EACH ROW BEGIN
    DECLARE acumulados_previos INT;
    DECLARE total_virtual INT;
    DECLARE cantidad_regalos INT;
    
    -- 1. Buscamos cuánto saldo tenía antes de esta compra
    SELECT IFNULL(garrafones_acumulados, 0) INTO acumulados_previos 
    FROM cliente_progreso_promo 
    WHERE codigo_cliente = NEW.codigo_cliente;

    -- 2. Sumamos lo que ya tenía + lo que compra hoy
    SET total_virtual = acumulados_previos + NEW.cantidad_garrafones;

    -- 3. Calculamos cuántos regalos le tocan (Ej: 45 / 10 = 4)
    SET cantidad_regalos = FLOOR(total_virtual / 10);

    -- 4. Aplicamos el descuento acumulado (15 * 4 = 60)
    SET NEW.descuento_aplicado = cantidad_regalos * 15.00;
    SET NEW.total_final = NEW.total_compra - NEW.descuento_aplicado;
END
$$
DELIMITER ;
DELIMITER $$
CREATE TRIGGER `tr_compra_descuenta_inventario` AFTER INSERT ON `compras` FOR EACH ROW BEGIN
  -- Descontar tapas
  UPDATE `inventario`
  SET `cantidad_actual` = `cantidad_actual` - NEW.cantidad_garrafones
  WHERE `id_insumo` = (SELECT id_insumo FROM insumos WHERE nombre = 'Tapa' LIMIT 1);

  -- Descontar liners
  UPDATE `inventario`
  SET `cantidad_actual` = `cantidad_actual` - NEW.cantidad_garrafones
  WHERE `id_insumo` = (SELECT id_insumo FROM insumos WHERE nombre = 'Liner' LIMIT 1);

  -- Registrar el movimiento de salida
  INSERT INTO `movimientos_inventario`
    (`id_insumo`, `tipo`, `cantidad`, `motivo`, `id_compra`)
  SELECT id_insumo, 'salida', NEW.cantidad_garrafones, 'Venta automatica', NEW.id_compra
  FROM `insumos` WHERE nombre IN ('Tapa', 'Liner');
END
$$
DELIMITER ;
DELIMITER $$
CREATE TRIGGER `tr_despues_de_insertar_compra` AFTER INSERT ON `compras` FOR EACH ROW BEGIN
    -- 1. Sumamos la cantidad nueva al saldo existente para CUALQUIER cliente
    INSERT INTO cliente_progreso_promo (codigo_cliente, garrafones_acumulados)
    VALUES (NEW.codigo_cliente, NEW.cantidad_garrafones)
    ON DUPLICATE KEY UPDATE 
    garrafones_acumulados = garrafones_acumulados + NEW.cantidad_garrafones;

    -- 2. Limpiamos los ciclos de 10 y registramos cada canje
    SET @acumulados = (SELECT garrafones_acumulados FROM cliente_progreso_promo WHERE codigo_cliente = NEW.codigo_cliente);

    WHILE @acumulados >= 10 DO
        INSERT INTO promociones_canjeadas (codigo_cliente, id_compra) 
        VALUES (NEW.codigo_cliente, NEW.id_compra);
        
        UPDATE cliente_progreso_promo 
        SET garrafones_acumulados = garrafones_acumulados - 10
        WHERE codigo_cliente = NEW.codigo_cliente;

        SET @acumulados = @acumulados - 10;
    END WHILE;
END
$$
DELIMITER ;

